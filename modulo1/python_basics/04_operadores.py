#Operadores Matemáticos
a = 15
b = 20
print("Suma")
print(a,"+", b, "=", a + b)
print("Resta")
print(a,"-", b, "=", a - b)
print("Multiplicación")
print(a,"*", b, "=", a * b)
print("División")
print(a,"/", b, "=", a / b)
print("Modulo")
print(a,"%", b, "=", a % b)
print("Operador de Asignación")
print("======================")
