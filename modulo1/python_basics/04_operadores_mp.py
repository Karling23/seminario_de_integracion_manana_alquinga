#Operadores Matemáticos
precio_moto1 = 1500
precio_moto2 = 2000
print("Suma")
print(precio_moto1,"+", precio_moto2, "=", precio_moto1 + precio_moto2)
print("Resta")
print(precio_moto1,"-", precio_moto2, "=", precio_moto1 - precio_moto2)
print("Multiplicación")
print(precio_moto1,"*", precio_moto2, "=", precio_moto1 * precio_moto2)
print("División")
print(precio_moto1,"/", precio_moto2, "=", precio_moto1 / precio_moto2)
print("Modulo")
print(precio_moto1,"%", precio_moto2, "=", precio_moto1 % precio_moto2)
print("Operador de Asignación")
print("======================")
stock = 10
stock += 5 
print("stock += 5:", stock)
stock -= 3
print("stock -= 3:", stock)
stock *= 2
print("stock *= 2:", stock)
stock /= 2
print("stock /= 2:", stock)
stock **= 2
print("stock **= 2:", stock)

#Operadores de Comparación
print("Operadores de Comparación")
print("=========================")
print("precio_moto1 == precio_moto2:", precio_moto1 == precio_moto2)
print("precio_moto1 != precio_moto2:", precio_moto1 != precio_moto2)
print("precio_moto1 < precio_moto2:", precio_moto1 < precio_moto2)
print("precio_moto1 > precio_moto2:", precio_moto1 > precio_moto2)
print("precio_moto1 <= precio_moto2:", precio_moto1 <= precio_moto2)
print("precio_moto1 >= precio_moto2:", precio_moto1 >= precio_moto2)

#Operadores logicos
print("Operadores Lógicos")
print("=================")
print("precio_moto1 and precio_moto2:", precio_moto1 and precio_moto2)
print("precio_moto1 or precio_moto2:", precio_moto1 or precio_moto2)
print("not precio_moto1:", not precio_moto1)
